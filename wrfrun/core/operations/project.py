from pathlib import Path

import tomli
import tomli_w

from ...model.plugins import load_model_plugin
from ...res import (
    CONFIG_ARPS_TOML_TEMPLATE,
    CONFIG_MAIN_TOML_TEMPLATE,
    CONFIG_PALM_TOML_TEMPLATE,
    CONFIG_ROMS_TOML_TEMPLATE,
    CONFIG_WRF_TOML_TEMPLATE,
    GITIGNORE_RULES,
)
from ..core import WRFRUN_NEW
from ..runtime.resource import PROJECT_TREE

MODEL_MAP = {
    "arps": CONFIG_ARPS_TOML_TEMPLATE,
    "wrf": CONFIG_WRF_TOML_TEMPLATE,
    "palm": CONFIG_PALM_TOML_TEMPLATE,
    "roms": CONFIG_ROMS_TOML_TEMPLATE,
}


def initialize_project(project_path: str | Path, models: list[str] | None = None) -> list[str]:
    """Create a project tree and its requested model configuration files."""
    project_path = Path(project_path).resolve()
    for directory in PROJECT_TREE:
        (project_path / directory).mkdir(exist_ok=True, parents=True)

    WRFRUN_NEW.io.copy(file_path=CONFIG_MAIN_TOML_TEMPLATE, save_path=project_path / "config.toml")
    WRFRUN_NEW.io.copy(file_path=GITIGNORE_RULES, save_path=project_path / ".gitignore")

    model_list = []
    for model_name in models or []:
        WRFRUN_NEW.io.copy(file_path=MODEL_MAP[model_name], save_path=project_path / f"configs/{model_name}.toml")
        load_model_plugin(model_name).initialize_project_files(project_path)
        (project_path / "data/inputs/common" / model_name).mkdir(exist_ok=True)
        model_list.append(model_name)

    return model_list


def add_models(config_path: str | Path, models: list[str]):
    """Add model configuration files and enable their model entries."""
    config_path = Path(config_path).resolve()
    project_path = config_path.parent

    with config_path.open("rb") as config_handle:
        main_config = tomli.load(config_handle)

    for model_name in models:
        if model_name not in main_config["model"]:
            main_config["model"][model_name] = {
                "note": (
                    "Config of this model is generated by wrfrun cli command. "
                    "DO NOT ADD CUSTOM CONFIG IN THIS SECTION because they may be overwrite by wrfrun cli tools."
                ),
                "use": True,
                "include": f"./configs/{model_name}.toml",
            }
        elif not ("use" in main_config["model"] and main_config["model"]["use"]):
            main_config["model"][model_name] = {
                "note": (
                    "Config of this model is generated by wrfrun cli command. "
                    "DO NOT ADD CUSTOM CONFIG IN THIS SECTION because they may be overwrite by wrfrun cli tools."
                ),
                "use": True,
                "include": f"./configs/{model_name}.toml",
            }

    config_dir_path = project_path / "configs"
    config_dir_path.mkdir(exist_ok=True, parents=True)
    for model_name in models:
        WRFRUN_NEW.io.copy(file_path=MODEL_MAP[model_name], save_path=config_dir_path / f"{model_name}.toml")
        load_model_plugin(model_name).initialize_project_files(project_path)
        (project_path / "data/inputs/common" / model_name).mkdir(exist_ok=True)

    with config_path.open("wb") as config_handle:
        tomli_w.dump(main_config, config_handle)


__all__ = ["MODEL_MAP", "add_models", "initialize_project"]
